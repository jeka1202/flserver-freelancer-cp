INSERT INTO warehouses (
    account_id,
    location_hash,
    location_type,
    location_name,
    item_hash,
    item_nickname,
    item_display_name,
    category,
    volume,
    mass,
    quantity,
    created_at,
    updated_at
)
SELECT
    'CHANGE_ME_ACCOUNT_ID' AS account_id,
    'CHANGE_ME_BASE_HASH_OR_NICKNAME' AS location_hash,
    'base' AS location_type,
    'CHANGE_ME_BASE_NAME' AS location_name,
    COALESCE(i.hash, nm.hash, s.item_token) AS item_hash,
    COALESCE(i.nickname, nm.nickname, s.item_token) AS item_nickname,
    COALESCE(NULLIF(i.display_name, ''), NULLIF(nm.display_name, ''), s.item_token) AS item_display_name,
    COALESCE(NULLIF(i.category, ''), NULLIF(nm.category, ''), 'craft') AS category,
    COALESCE(i.volume, 0) AS volume,
    COALESCE(i.mass, 0) AS mass,
    s.quantity,
    datetime('now') AS created_at,
    datetime('now') AS updated_at
FROM warehouse_seed_items s
LEFT JOIN items i
       ON i.hash = s.item_token
       OR i.nickname = s.item_token
       OR i.good_nickname = s.item_token
       OR i.equipment_nickname = s.item_token
LEFT JOIN name_map nm
       ON nm.token = s.item_token
WHERE COALESCE(i.hash, nm.hash, s.item_token) IS NOT NULL
ON CONFLICT(account_id, location_hash, item_hash)
DO UPDATE SET
    quantity = excluded.quantity,
    location_name = excluded.location_name,
    item_nickname = excluded.item_nickname,
    item_display_name = excluded.item_display_name,
    category = excluded.category,
    volume = excluded.volume,
    mass = excluded.mass,
    updated_at = excluded.updated_at;

DROP TABLE warehouse_seed_items;

COMMIT;
